import SwiftUI

// Generate the standalone Contract styles from the same resolved tokens SwiftUI renders.
// Run scripts/export-bubble-style.sh --write after a deliberate design-token change.
@main
struct BubbleStyleExport {
  typealias Style = MessagesStyle

  static func css(_ color: Color) -> String {
    var environment = EnvironmentValues()
    environment.colorScheme = .dark
    let resolved = color.resolve(in: environment)
    let bytes = [resolved.red, resolved.green, resolved.blue, resolved.opacity]
      .map { UInt8(clamping: Int((Double($0) * 255).rounded())) }
    return "#" + (bytes[3] == 255 ? bytes.prefix(3) : bytes.prefix(4))
      .map { String(format: "%02X", $0) }.joined()
  }

  static func number(_ n: Double) -> String {
    String(format: "%.5f", locale: Locale(identifier: "en_US_POSIX"), n)
      .replacingOccurrences(of: #"\.?0+$"#, with: "", options: .regularExpression)
  }

  static func main() {
    let gradient = Style.outgoingFillColors.map(css).joined(separator: ", ")
    let textPadding = "\(number(Style.bubbleInset))px \(number(Style.bubbleHorizontalInset))px"
    let typingPadding = "\(number(Style.typingBubbleVerticalInset))px \(number(Style.typingBubbleHorizontalInset))px"
    let hairline = "\(number(Style.bubbleBorderWidth))px solid \(css(Style.incomingBorder))"
    let connector = "\(number(Style.replyConnectorStroke))px solid \(css(Style.secondary.opacity(Style.replyPreviewOpacity)))"
    let badge = number(Style.tapbackBadgeCircle)
    print("""
    // Generated by scripts/export-bubble-style.sh from NessaDesignSystem. Edit the Swift tokens.
    fn bubbleFill(sent: bool): string = sent ? "\(css(Style.outgoing))" : "\(css(Style.incoming))"
    fn bubbleGradient(sent: bool): string = sent ? "linear-gradient(180deg, \(gradient))" : "none"
    fn bubbleBorderWidth(sent: bool): number = sent ? 0 : \(number(Style.bubbleBorderWidth))
    fn bubbleBorderInk(): string = "\(css(Style.incomingBorder))"
    fn quoteFill(sent: bool): string = sent ? "\(css(Style.outgoing.opacity(Style.replyPreviewOpacity)))" : "\(css(Style.incoming.opacity(Style.replyPreviewOpacity)))"
    fn bubbleBackground(): string = "\(css(Style.background))"
    fn bubbleControl(): string = "\(css(Style.control))"
    fn bubbleInset(): number = \(number(Style.bubbleInset))
    fn bubbleGutter(): number = \(number(Style.bubbleGutter))
    fn photoWidth(): number = \(number(Style.photoWidth))
    fn photoStackHeight(): number = \(number(Style.photoStackHeight))
    fn photoStackTilt(): number = \(number(Style.photoStackTilt))
    fn photoRadius(): number = \(number(Style.photoRadius))
    fn gallerySpacing(): number = \(number(Style.gallerySpacing))
    fn reactionClearance(): number = \(number(Style.reactionClearance))
    fn tapbackInk(): string = "\(css(Style.tapbackBackground))"
    fn typingCycleMS(): number = \(number(Style.typingCycle * 1000))
    fn typingStepMS(): number = \(number(Style.typingStep * Style.typingCycle * 1000))

    style BubbleTextSurface
      padding="\(textPadding)" border-radius=\(number(Style.bubbleRadius))
    style BubbleInk
      color="\(css(Style.foreground))"
    style FileBubbleSurface
      gap=\(number(NessaSpacing.xs)) padding=\(number(Style.bubbleInset)) border-radius=\(number(Style.replyPreviewRadius)) background-color="\(css(Style.control))"
    style QuoteBubbleSurface
      padding=\(number(Style.bubbleInset)) border-radius=\(number(Style.replyPreviewRadius))
    style QuoteInk
      color="\(css(Style.secondary))"
    style QuoteConnector
      width=\(number(Style.replyConnectorWidth)) height=\(number(Style.replyConnectorHeight)) margin="0px \(number(Style.bubbleInset))px" border-left="\(connector)" border-bottom="\(connector)" border-bottom-left-radius=\(number(Style.replyConnectorHeight / 2))
    style BubbleMessageSpacing
      gap=\(number(NessaSpacing.xs))
    style BubbleQuoteSpacing
      gap=\(number(NessaSpacing.xxs))
    style BubbleReplyCount
      padding="0px \(number(Style.bubbleInset))px" color="\(css(Style.tapbackBackground))"
    style BubbleTypingSurface
      gap=\(number(Style.typingDotSpacing)) padding="\(typingPadding)" border-radius=\(number(Style.bubbleRadius)) background-color="\(css(Style.incoming))" border="\(hairline)"
    style TypingTailLarge
      left=\(number(-Style.typingTailLarge / 4)) bottom=\(number(-Style.typingTailLarge / 4)) width=\(number(Style.typingTailLarge)) height=\(number(Style.typingTailLarge)) border-radius=\(number(Style.typingTailLarge / 2)) background-color="\(css(Style.incoming))" border="\(hairline)"
    style TypingTailSmall
      left=\(number(-Style.typingTailLarge / 2)) bottom=\(number(-Style.typingTailLarge * 3 / 4)) width=\(number(Style.typingTailSmall)) height=\(number(Style.typingTailSmall)) border-radius=\(number(Style.typingTailSmall / 2)) background-color="\(css(Style.incoming))" border="\(hairline)"
    style TypingDot
      width=\(number(Style.typingDotSize)) height=\(number(Style.typingDotSize)) border-radius=\(number(Style.typingDotSize / 2)) background-color="\(css(Style.secondary))" opacity=\(number(Style.typingDotRestOpacity))
    style TapbackCircle
      top=\(number(Style.reactionOffset)) width=\(badge) height=\(badge) border-radius=\(number(Style.tapbackBadgeCircle / 2)) background-color="\(css(Style.tapbackBackground))"
    keyframes typingPulse
      from opacity=\(number(Style.typingDotRestOpacity)) scale=1
      \(number(Style.typingPulse * 50))% opacity=1 scale=\(number(Style.typingDotPeakScale))
      \(number(Style.typingPulse * 100))% opacity=\(number(Style.typingDotRestOpacity)) scale=1
      to opacity=\(number(Style.typingDotRestOpacity)) scale=1
    """)
  }
}
